def _migrate_sqlite(con: Conn) -> None:
    """Pasa una base SQLite de la versión anterior (con revisores y enlaces personales) a la actual."""
    cols = {r["name"] for r in con.execute("PRAGMA table_info(users)")}
    if "name" in cols and "email" not in cols:
        con.execute("ALTER TABLE users RENAME COLUMN name TO email")
        stale = ("SELECT id FROM users WHERE email NOT LIKE '%@%' AND email <> 'admin' "
                 "AND id NOT IN (SELECT user_id FROM annotations)")
        con.execute(f"DELETE FROM assignments WHERE user_id IN ({stale})")
        con.execute(f"DELETE FROM choice_memory WHERE user_id IN ({stale})")
        con.execute(f"DELETE FROM users WHERE id IN ({stale})")
        con.execute("UPDATE users SET role='annotator' WHERE role<>'annotator' AND email<>'admin'")
        con.commit()
    # Las tablas del catálogo ahora viven en catalog.db; si quedaron en la base vieja, sobran.
    for t in ("catalog_kw", "catalog"):
        con.execute(f"DROP TABLE IF EXISTS {t}")
    con.execute("DELETE FROM settings WHERE key LIKE 'catalog\\_%' ESCAPE '\\'")
    con.commit()


def init_db(path=None) -> None:
    con = connect(path)
    try:
        if con.engine == "sqlite":
            con.executescript(SQLITE_SCHEMA)
            _migrate_sqlite(con)
        else:
            con.execute("SELECT pg_advisory_xact_lock(4243)")  # dos arranques a la vez no chocan
            con.executescript(PG_SCHEMA)
        con.commit()
    finally:
        con.close()


def drop_all(con: Conn) -> None:
    """Solo para pruebas: deja la base vacía."""
    for t in ALL_TABLES:
        con.execute(f"DROP TABLE IF EXISTS {t}" + (" CASCADE" if con.engine == "postgres" else ""))
    con.commit()


def get_db():
    """Dependencia de FastAPI: una conexión por petición (del pool, si es PostgreSQL)."""
    con = connect()
    try:
        yield con
    finally:
        con.close()


def get_setting(con, key, default=None):
    row = con.execute("SELECT value FROM settings WHERE key=?", (key,)).fetchone()
    return row["value"] if row else default


def set_setting(con, key, value) -> None:
    con.execute(
        "INSERT INTO settings(key,value) VALUES(?,?) "
        "ON CONFLICT(key) DO UPDATE SET value=excluded.value",
        (key, str(value)),
    )
