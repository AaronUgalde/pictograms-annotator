"""Base de datos de la aplicación: alumnos, oraciones, asignaciones, respuestas, memoria y ajustes.

Dos motores con el mismo código:
- PostgreSQL (p. ej. Neon) si está definida DATABASE_URL. Es lo que se usa en Render gratis,
  donde el disco se borra en cada reinicio.
- SQLite (archivo data/annotator.db) en cualquier otro caso: desarrollo local o servidor con disco propio.

Las consultas se escriben con marcadores «?»; para PostgreSQL se traducen a «%s».
El catálogo de pictogramas NO vive aquí: va en un SQLite local aparte (ver catalog.py).
"""
import secrets
import sqlite3
import threading
from datetime import datetime, timezone

from . import config

_TABLES = """
CREATE TABLE IF NOT EXISTS users (
    id {pk},
    email TEXT UNIQUE NOT NULL,          -- correo en minúsculas (el administrador usa 'admin')
    token TEXT UNIQUE NOT NULL,
    role TEXT NOT NULL DEFAULT 'annotator' CHECK (role IN ('annotator','admin')),
    active INTEGER NOT NULL DEFAULT 1,
    created_at TEXT NOT NULL
);

CREATE TABLE IF NOT EXISTS sentences (
    id {pk},
    text TEXT NOT NULL UNIQUE,
    created_at TEXT NOT NULL
);

CREATE TABLE IF NOT EXISTS assignments (
    id {pk},
    sentence_id INTEGER NOT NULL REFERENCES sentences(id) ON DELETE CASCADE,
    user_id INTEGER NOT NULL REFERENCES users(id),
    seq INTEGER NOT NULL,
    UNIQUE (sentence_id, user_id)
);
CREATE INDEX IF NOT EXISTS idx_assign_user ON assignments(user_id, seq);

CREATE TABLE IF NOT EXISTS annotations (
    id {pk},
    sentence_id INTEGER NOT NULL REFERENCES sentences(id) ON DELETE CASCADE,
    user_id INTEGER NOT NULL REFERENCES users(id),
    status TEXT NOT NULL CHECK (status IN ('done','doubtful','skipped')),
    note TEXT NOT NULL DEFAULT '',
    proposal TEXT,                       -- JSON con los IDs propuestos por el sistema
    from_suggestion INTEGER NOT NULL DEFAULT 0,
    accepted_unchanged INTEGER NOT NULL DEFAULT 0,
    seconds REAL NOT NULL DEFAULT 0,
    catalog_version TEXT NOT NULL,
    guide_version TEXT NOT NULL,
    created_at TEXT NOT NULL,
    updated_at TEXT NOT NULL,
    UNIQUE (sentence_id, user_id)
);
CREATE INDEX IF NOT EXISTS idx_annotations_user ON annotations(user_id);

CREATE TABLE IF NOT EXISTS annotation_items (
    annotation_id INTEGER NOT NULL REFERENCES annotations(id) ON DELETE CASCADE,
    position INTEGER NOT NULL,
    picto_id INTEGER NOT NULL,
    keyword TEXT NOT NULL DEFAULT '',
    token TEXT,
    PRIMARY KEY (annotation_id, position)
);

CREATE TABLE IF NOT EXISTS choice_memory (
    lemma TEXT NOT NULL,
    picto_id INTEGER NOT NULL,
    user_id INTEGER NOT NULL,
    count INTEGER NOT NULL DEFAULT 0,
    last_used TEXT NOT NULL,
    PRIMARY KEY (lemma, picto_id, user_id)
);

CREATE TABLE IF NOT EXISTS settings (
    key TEXT PRIMARY KEY,
    value TEXT NOT NULL
);
"""

SQLITE_SCHEMA = _TABLES.format(pk="INTEGER PRIMARY KEY")
PG_SCHEMA = _TABLES.format(pk="INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY")
ALL_TABLES = ["annotation_items", "annotations", "assignments", "choice_memory", "settings", "sentences", "users"]


def now() -> str:
    return datetime.now(timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ")


def new_token() -> str:
    return secrets.token_urlsafe(16)


def using_postgres() -> bool:
    return bool(config.DATABASE_URL)


def kind() -> str:
    return "postgres" if using_postgres() else "sqlite"


# ------------------------------------------------------------------ conexión unificada

class _PgRow(dict):
    """Fila que se lee por nombre (r["email"]) o por posición (r[0]), como sqlite3.Row."""
    __slots__ = ("_values",)

    def __init__(self, names, values):
        super().__init__(zip(names, values))
        self._values = values

    def __getitem__(self, key):
        if isinstance(key, int):
            return self._values[key]
        return super().__getitem__(key)


def _pg_row_factory(cursor):
    names = [c.name for c in cursor.description] if cursor.description else []
    return lambda values: _PgRow(names, values)


class Conn:
    """Misma interfaz para SQLite y PostgreSQL: execute(sql con «?»), commit(), rollback(), close()."""

    def __init__(self, raw, engine: str, release=None):
        self.raw = raw
        self.engine = engine
        self._release = release

    def execute(self, sql: str, params=()):
        if self.engine == "sqlite":
            return self.raw.execute(sql, params)
        params = tuple(params) if params else None
        if params is not None:
            sql = sql.replace("%", "%%").replace("?", "%s")
        return self.raw.execute(sql, params)

    def executescript(self, script: str):
        if self.engine == "sqlite":
            return self.raw.executescript(script)
        for stmt in script.split(";"):
            body = "\n".join(l for l in stmt.splitlines() if not l.strip().startswith("--")).strip()
            if body:
                self.raw.execute(stmt)

    def commit(self):
        self.raw.commit()

    def rollback(self):
        self.raw.rollback()

    def lock(self):
        """Empieza una transacción exclusiva (para repartir oraciones sin que dos alumnos reciban lo mismo)."""
        self.raw.commit()
        if self.engine == "sqlite":
            self.raw.execute("BEGIN IMMEDIATE")
        else:
            self.raw.execute("SELECT pg_advisory_xact_lock(4242)")

    def close(self):
        if self._release:
            try:
                if not self.raw.closed and self.raw.info.transaction_status != 0:  # 0 = IDLE
                    self.raw.rollback()  # lecturas sin commit: se cierra la transacción antes de devolverla
            except Exception:
                pass
            self._release(self.raw)
        else:
            self.raw.close()


_pool = None
_pool_lock = threading.Lock()


def _get_pool():
    global _pool
    with _pool_lock:
        if _pool is None:
            from psycopg_pool import ConnectionPool

            _pool = ConnectionPool(
                config.DATABASE_URL,
                min_size=0,          # sin conexiones abiertas en reposo: Neon puede dormirse y no gasta horas
                max_size=8,
                max_idle=120,
                timeout=30,
                check=ConnectionPool.check_connection,  # descarta conexiones que Neon cerró al dormirse
                kwargs={"row_factory": _pg_row_factory, "prepare_threshold": None, "connect_timeout": 15},
                open=True,
            )
        return _pool


def close_pool() -> None:
    global _pool
    with _pool_lock:
        if _pool is not None:
            _pool.close()
            _pool = None


def connect(path=None) -> Conn:
    """Conexión a la base de la aplicación. Con `path` siempre es SQLite (útil en pruebas y migraciones)."""
    if path is None and using_postgres():
        pool = _get_pool()
        return Conn(pool.getconn(), "postgres", release=pool.putconn)
    path = path or config.DB_PATH
    path.parent.mkdir(parents=True, exist_ok=True)
    raw = sqlite3.connect(path, timeout=10, check_same_thread=False)
    raw.row_factory = sqlite3.Row
    raw.execute("PRAGMA journal_mode=WAL")
    raw.execute("PRAGMA synchronous=NORMAL")
    raw.execute("PRAGMA foreign_keys=ON")
    raw.execute("PRAGMA busy_timeout=5000")
    return Conn(raw, "sqlite")


