"""Base de datos PostgreSQL (Neon): alumnos, oraciones, asignaciones, respuestas, memoria y ajustes.

La conexión se toma de DATABASE_URL. Las consultas se escriben con marcadores «?» y aquí se
traducen a «%s», el formato de psycopg. El catálogo de pictogramas no vive aquí (ver catalog.py).
"""
import secrets
import threading
from datetime import datetime, timezone

from . import config

SCHEMA = """
CREATE TABLE IF NOT EXISTS users (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email TEXT UNIQUE NOT NULL,          -- correo en minúsculas (el administrador usa 'admin')
    token TEXT UNIQUE NOT NULL,
    role TEXT NOT NULL DEFAULT 'annotator' CHECK (role IN ('annotator','admin')),
    active INTEGER NOT NULL DEFAULT 1,
    created_at TEXT NOT NULL
);

CREATE TABLE IF NOT EXISTS sentences (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    text TEXT NOT NULL UNIQUE,
    created_at TEXT NOT NULL
);

CREATE TABLE IF NOT EXISTS assignments (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sentence_id INTEGER NOT NULL REFERENCES sentences(id) ON DELETE CASCADE,
    user_id INTEGER NOT NULL REFERENCES users(id),
    seq INTEGER NOT NULL,
    UNIQUE (sentence_id, user_id)
);
CREATE INDEX IF NOT EXISTS idx_assign_user ON assignments(user_id, seq);

CREATE TABLE IF NOT EXISTS annotations (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sentence_id INTEGER NOT NULL REFERENCES sentences(id) ON DELETE CASCADE,
    user_id INTEGER NOT NULL REFERENCES users(id),
    status TEXT NOT NULL CHECK (status IN ('done','doubtful','skipped')),
    note TEXT NOT NULL DEFAULT '',
    proposal TEXT,                       -- JSON con los IDs propuestos por el sistema
    from_suggestion INTEGER NOT NULL DEFAULT 0,
    accepted_unchanged INTEGER NOT NULL DEFAULT 0,
    seconds REAL NOT NULL DEFAULT 0,
    catalog_version TEXT NOT NULL,
    guide_version TEXT NOT NULL,
    created_at TEXT NOT NULL,
    updated_at TEXT NOT NULL,
    UNIQUE (sentence_id, user_id)
);
CREATE INDEX IF NOT EXISTS idx_annotations_user ON annotations(user_id);

CREATE TABLE IF NOT EXISTS annotation_items (
    annotation_id INTEGER NOT NULL REFERENCES annotations(id) ON DELETE CASCADE,
    position INTEGER NOT NULL,
    picto_id INTEGER NOT NULL,
    keyword TEXT NOT NULL DEFAULT '',
    token TEXT,
    PRIMARY KEY (annotation_id, position)
);

CREATE TABLE IF NOT EXISTS choice_memory (
    lemma TEXT NOT NULL,
    picto_id INTEGER NOT NULL,
    user_id INTEGER NOT NULL,
    count INTEGER NOT NULL DEFAULT 0,
    last_used TEXT NOT NULL,
    PRIMARY KEY (lemma, picto_id, user_id)
);

CREATE TABLE IF NOT EXISTS settings (
    key TEXT PRIMARY KEY,
    value TEXT NOT NULL
);
"""

ALL_TABLES = ["annotation_items", "annotations", "assignments", "choice_memory", "settings", "sentences", "users"]


class MissingDatabaseUrl(RuntimeError):
    pass


def now() -> str:
    return datetime.now(timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ")


def new_token() -> str:
    return secrets.token_urlsafe(16)


# ------------------------------------------------------------------ conexión

class _Row(dict):
    """Fila que se lee por nombre (r["email"]) o por posición (r[0])."""
    __slots__ = ("_values",)

    def __init__(self, names, values):
        super().__init__(zip(names, values))
        self._values = values

    def __getitem__(self, key):
        if isinstance(key, int):
            return self._values[key]
        return super().__getitem__(key)


def _row_factory(cursor):
    names = [c.name for c in cursor.description] if cursor.description else []
    return lambda values: _Row(names, values)


class Conn:
    """Envoltorio de una conexión psycopg: execute(sql con «?»), commit(), rollback(), lock(), close()."""

    def __init__(self, raw, release):
        self.raw = raw
        self._release = release

    def execute(self, sql: str, params=()):
        params = tuple(params) if params else None
        if params is not None:
            sql = sql.replace("%", "%%").replace("?", "%s")
        return self.raw.execute(sql, params)

    def executescript(self, script: str):
        for stmt in script.split(";"):
            body = "\n".join(l for l in stmt.splitlines() if not l.strip().startswith("--")).strip()
            if body:
                self.raw.execute(stmt)

    def commit(self):
        self.raw.commit()

    def rollback(self):
        self.raw.rollback()

    def lock(self):
        """Empieza una transacción exclusiva (para repartir oraciones sin que dos alumnos reciban lo mismo)."""
        self.raw.commit()
        self.raw.execute("SELECT pg_advisory_xact_lock(4242)")

    def close(self):
        try:
            if not self.raw.closed and self.raw.info.transaction_status != 0:  # 0 = sin transacción abierta
                self.raw.rollback()  # lecturas sin commit: se cierra la transacción antes de devolverla
        except Exception:
            pass
        self._release(self.raw)


_pool = None
_pool_lock = threading.Lock()


def _get_pool():
    global _pool
    if not config.DATABASE_URL:
        raise MissingDatabaseUrl(
            "Falta DATABASE_URL: define la cadena de conexión de PostgreSQL (Neon), "
            "por ejemplo postgresql://usuario:clave@servidor/neondb?sslmode=require")
    with _pool_lock:
        if _pool is None:
            from psycopg_pool import ConnectionPool

            _pool = ConnectionPool(
                config.DATABASE_URL,
                min_size=0,          # sin conexiones abiertas en reposo: Neon puede dormirse y no gasta horas
                max_size=8,
                max_idle=120,
                timeout=30,
                check=ConnectionPool.check_connection,  # descarta conexiones que Neon cerró al dormirse
                kwargs={"row_factory": _row_factory, "prepare_threshold": None, "connect_timeout": 15},
                open=True,
            )
        return _pool


def close_pool() -> None:
    global _pool
    with _pool_lock:
        if _pool is not None:
            _pool.close()
            _pool = None


def connect() -> Conn:
    pool = _get_pool()
    return Conn(pool.getconn(), release=pool.putconn)


# ------------------------------------------------------------------ esquema

def init_db() -> None:
    """Crea las tablas si no existen (seguro aunque arranquen dos servidores a la vez)."""
    con = connect()
    try:
        con.execute("SELECT pg_advisory_xact_lock(4243)")
        con.executescript(SCHEMA)
        con.commit()
    finally:
        con.close()


def drop_all(con: Conn) -> None:
    """Deja la base vacía (pruebas y reseteo con `manage.py reset`)."""
    for t in ALL_TABLES:
        con.execute(f"DROP TABLE IF EXISTS {t} CASCADE")
    con.commit()


def get_db():
    """Dependencia de FastAPI: una conexión del pool por petición."""
    con = connect()
    try:
        yield con
    finally:
        con.close()


def get_setting(con, key, default=None):
    row = con.execute("SELECT value FROM settings WHERE key=?", (key,)).fetchone()
    return row["value"] if row else default


def set_setting(con, key, value) -> None:
    con.execute(
        "INSERT INTO settings(key,value) VALUES(?,?) "
        "ON CONFLICT(key) DO UPDATE SET value=excluded.value",
        (key, str(value)),
    )
